import { chmod, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HOST_NAME = 'com.quolabo.booth_cookie_sync';
const SYNC_DIR = dirname(fileURLToPath(import.meta.url));
const quote = value => `'${value.replaceAll("'", "'\\''")}'`;

async function existingManifest(path) {
  try {
    return JSON.parse(await readFile(path, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw new Error(`Cannot read existing host registration: ${path}`, { cause: error });
  }
}

// Parameters allow isolated installation checks without changing a browser profile.
export async function installMac({ homeDir = homedir(), syncDir = SYNC_DIR, nodePath = process.execPath, uninstall = false } = {}) {
  const launcher = join(resolve(syncDir), 'host', 'run-host.sh');
  const hostScript = join(resolve(syncDir), 'host', 'host.js');
  const manifestDir = join(homeDir, 'Library', 'Application Support', 'Google', 'Chrome', 'NativeMessagingHosts');
  const manifestPath = join(manifestDir, `${HOST_NAME}.json`);
  const previous = await existingManifest(manifestPath);
  if (previous && (previous.name !== HOST_NAME || previous.path !== launcher)) {
    throw new Error(`Another installation owns ${manifestPath}. Uninstall it from its original directory first.`);
  }
  if (uninstall) {
    if (previous) await rm(manifestPath);
    await rm(launcher, { force: true });
    return { manifestPath, removed: Boolean(previous) };
  }
  await readFile(hostScript); // Check the installation before writing any registration.
  const template = JSON.parse(await readFile(join(syncDir, 'host', `${HOST_NAME}.json.template`), 'utf8'));
  template.path = launcher;
  const script = `#!/bin/sh\n# Generated by booth-cookie-sync/install-macos.mjs. Re-run after moving Node or this repository.\nexec ${quote(nodePath)} ${quote(hostScript)} "$@"\n`;
  await writeFile(launcher, script, { mode: 0o700 });
  await chmod(launcher, 0o700);
  await mkdir(manifestDir, { recursive: true, mode: 0o700 });
  const temporary = `${manifestPath}.${process.pid}.tmp`;
  try {
    await writeFile(temporary, `${JSON.stringify(template, null, 2)}\n`, { mode: 0o600 });
    await rename(temporary, manifestPath);
  } finally {
    await rm(temporary, { force: true });
  }
  return { manifestPath, launcher, nodePath };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    if (process.platform !== 'darwin') throw new Error('This installer is for macOS. On Windows use install.ps1.');
    const args = process.argv.slice(2);
    if (args.length > 1 || (args.length === 1 && args[0] !== '--uninstall')) {
      throw new Error('Usage: sh booth-cookie-sync/install.sh [--uninstall]');
    }
    const result = await installMac({ uninstall: args[0] === '--uninstall' });
    console.log(`${args[0] === '--uninstall' ? 'Removed' : 'Registered'}: ${result.manifestPath}`);
    if (!args.length) {
      console.log(`Chrome will use Node at: ${result.nodePath}`);
      console.log(`Load unpacked extension from: ${join(SYNC_DIR, 'extension')}`);
      console.log('Open chrome://extensions, enable Developer mode, and load the extension.');
      console.log('Log in to manage.booth.pm, then click the extension icon to sync.');
      console.log('If the host is not found, fully quit Chrome (Command-Q) and reopen it.');
    } else {
      console.log('Remove the extension in chrome://extensions. Cookie files are preserved.');
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
